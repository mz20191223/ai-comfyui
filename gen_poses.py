import os
os.makedirs(OUT, exist_ok=True)

def draw_pose(name, joints):
    img = Image.new("RGB", (W, H), (0, 0, 0))
    d = ImageDraw.Draw(img)
    # 连线
    for a, b in EDGES:
        pa, pb = joints.get(a), joints.get(b)
        if pa and pb:
            d.line([pa, pb], fill=(255, 255, 255), width=8)
    # 关节圆点
    for k, p in joints.items():
        if p:
            d.ellipse([p[0]-10, p[1]-10, p[0]+10, p[1]+10], fill=(255, 255, 255))
    path = os.path.join(OUT, f"{name}.png")
    img.save(path)
    print("saved", path)

for name, joints in POSES.items():
    draw_pose(name, joints)

