/**
 * 全局常量：短剧题材预设。
 *
 * 用途：新建/编辑项目、剧本页「可选参数」的「题材」下拉。
 * 注意：下拉是 filterable + allow-create 的，预设只是"常见值快捷入口"，
 * 用户可以自己敲任意新题材；`genreOptions()` 会把当前值并进列表，
 * 保证历史项目里已有的自定义题材也能正常显示成选中项。
 */
export const GENRES = [
  '都市',
  '都市异能',
  '悬疑',
  '悬疑推理',
  '软科幻',
  '硬科幻',
  '末日科幻',
  '古装',
  '宫斗',
  '武侠',
  '仙侠',
  '玄幻',
  '神话',
  '奇幻',
  '穿越',
  '重生',
  '复仇',
  '甜宠',
  '虐恋',
  '年代',
  '民国',
  '职场',
  '商战',
  '家庭',
  '校园',
  '军旅',
  '犯罪',
  '搞笑',
]

/** 下拉选项：当前值（不在预设里时）排在最前 + 全部预设 */
export function genreOptions(current) {
  const v = String(current || '').trim()
  return v && !GENRES.includes(v) ? [v, ...GENRES] : GENRES
}
